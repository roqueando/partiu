"""Ports — abstract interfaces the application layer depends on.

These are :class:`typing.Protocol` declarations (structural subtyping), so any
adapter that implements the methods satisfies the port without inheriting from
an abstract base. Use cases receive these ports via parameter injection; the
composition root (:mod:`partiu.main`) binds concrete adapters.

Inputs/outputs are expressed in domain terms (see ``data-model.md``). Adapters
translate their native formats (SQL rows, PDF pages, spreadsheet cells, camera
frames) into these shapes at the boundary.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any, Protocol


class PartRepository(Protocol):
    """Persistence for parts (and their pins/parameters/attachments)."""

    def list_parts(self, search: str | None = None) -> list[dict[str, Any]]: ...
    def get_part(self, pk: int) -> dict[str, Any] | None: ...
    def create_part(self, data: dict[str, Any]) -> dict[str, Any]: ...
    def update_part(self, pk: int, data: dict[str, Any]) -> dict[str, Any]: ...
    def delete_part(self, pk: int) -> None: ...
    def import_parts(self, rows: list[dict[str, Any]]) -> dict[str, int]: ...


class StockRepository(Protocol):
    """Persistence for stock items and stock locations."""

    def list_stock_items(self, search: str | None = None) -> list[dict[str, Any]]: ...
    def create_stock_item(self, data: dict[str, Any]) -> dict[str, Any]: ...
    def update_stock_item(self, pk: int, data: dict[str, Any]) -> dict[str, Any]: ...
    def delete_stock_item(self, pk: int) -> None: ...
    def set_stock_items_location(self, pks: list[int], location_id: int | None) -> None: ...
    def create_stock_items_for_all_parts(self) -> int: ...
    def list_stock_locations(self, search: str | None = None) -> list[dict[str, Any]]: ...
    def create_stock_location(self, data: dict[str, Any]) -> dict[str, Any]: ...
    def update_stock_location(self, pk: int, data: dict[str, Any]) -> dict[str, Any]: ...
    def delete_stock_location(self, pk: int) -> None: ...


class RepairRepository(Protocol):
    """Persistence for repair projects, photos, and findings."""

    def list_repair_projects(self) -> list[dict[str, Any]]: ...
    def get_repair_project(self, pk: int) -> dict[str, Any] | None: ...
    def create_repair_project(self, data: dict[str, Any]) -> dict[str, Any]: ...
    def update_repair_project(self, pk: int, data: dict[str, Any]) -> dict[str, Any]: ...
    def delete_repair_project(self, pk: int) -> None: ...
    def add_repair_photo(self, project_id: int, source_path: Path) -> dict[str, Any]: ...
    def list_repair_photos(self, project_id: int) -> list[dict[str, Any]]: ...
    def repair_photo_path(self, pk: int) -> Path | None: ...
    def delete_repair_photo(self, pk: int) -> None: ...
    def list_repair_annotations(self, project_id: int) -> list[dict[str, Any]]: ...
    def replace_repair_annotations(self, project_id: int, rows: list[dict[str, Any]]) -> None: ...


class AttachmentStore(Protocol):
    """File attachments (photos / datasheets) stored alongside the database."""

    def list_attachments(self, part_id: int) -> list[dict[str, Any]]: ...
    def attachment_path(self, pk: int) -> Path | None: ...
    def set_attachment(self, part_id: int, kind: str, source_path: Path) -> dict[str, Any]: ...
    def delete_attachment(self, pk: int) -> None: ...
    def get_attachment(self, part_id: int, kind: str) -> dict[str, Any] | None: ...


class DatasheetExtractor(Protocol):
    """Extract component data from a PDF datasheet."""

    def extract(
        self,
        pdf_path: Path | str,
        part_name: str | None = None,
        part_ipn: str | None = None,
    ) -> dict[str, Any]: ...


class PartsImporter(Protocol):
    """Read parts from spreadsheet files and write the import template."""

    def read_parts(self, path: Path) -> list[dict[str, Any]]: ...
    def write_template(self, path: Path) -> None: ...


class SettingsStore(Protocol):
    """Persist small user preferences."""

    def get(self, key: str, default: Any = None) -> Any: ...
    def set(self, key: str, value: Any) -> None: ...


class CameraCapturer(Protocol):
    """Camera driver (frame capture), independent of any GUI toolkit."""

    def list_cameras(self) -> list[tuple[int, str]]: ...
    def open(self, index: int) -> bool: ...
    def read_frame(self) -> Any: ...
    def close(self) -> None: ...
